function t(key, vars = {}) {
  const text = I18N[LANG][key] ?? I18N.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? vars[name] : m));
}

function tn(key, n, vars = {}) {  // plural: key_one / key_other
  return t(`${key}_${n === 1 ? "one" : "other"}`, Object.assign({n}, vars));
}

function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-text]").forEach(el => { el.dataset.text = t(el.dataset.i18nText); });
}

